#!/usr/bin/env python3
"""Every quoted #include under src/ must resolve to a file that exists.

A quoted include that resolves to nothing is a hard compile error, and it is the failure mode a
merge produces most quietly: the including file is not itself conflicted, so git reports no
conflict, and the breakage only appears on the next build of the affected target. The CEF
deletion moved headers between directories and a stale relative path survived exactly that way.

Resolution order is the one the compiler uses: relative to the including file first, then to the
include root (src/, given as -Isrc by xmake), then to the Ultralight SDK include root, then to
tests/ for the hosted unit tests that compile a src/ translation unit with -Itests.

Externals are exempt by name -- CommonLibF4's RE/* headers and the vendor SDKs are not in this
repository, and neither is a defect this guard can or should adjudicate.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"

INCLUDE = re.compile(r'^\s*#\s*include\s*"([^"]+)"', re.M)

# Include roots the build puts on the compiler command line, in order. src/ is the framework's
# own root; the SDK roots are the two external directories xmake adds for pch/sdk headers.
SDK_ROOTS = (
    ROOT / "external" / "ultralight-1.4.0" / "include",
    ROOT / "external" / "ultralight-1.4.0" / "include" / "Ultralight",
)

# Non-repository externals. Each entry is a (regex, reason) pair matched against the include text.
EXTERNAL = (
    (re.compile(r"^RE/"), "CommonLibF4 reverse-engineering headers are an external submodule"),
    (re.compile(r"^F4SE/"), "F4SE public SDK headers are external"),
    (re.compile(r"^REL/"), "CommonLibF4 REL headers are an external submodule"),
    (re.compile(r"^(Ultralight/|AppCore/|JavaScriptCore/)"),
     "the vendored Ultralight 1.4 SDK is external and not committed"),
    (re.compile(r"^(CK/|SKSE/|DirectXTK/|d3d|dxgi|wrl/|windows\.h|bcrypt\.h)"),
     "platform/SDK headers come from the toolchain"),
)

# Includes that resolve only on the build machine, with the reason. Keep this list short and
# justified: anything here is a hole in the guard.
ALLOWED_UNRESOLVED = {
    # Generated at configure time by xmake from runtime/ultralight-1.4.0.manifest.json.
    "PrismaUI/UltralightRuntimeManifest.g.h": "generated by xmake from the pinned runtime manifest",
}

HOSTED_TEST_BRANCHES = {
    "PRISMAUI_FLAT_API_HOST_TEST": {"flat_api_host_api.h"},
    "PRISMAUI_MODELPREVIEW_READS_TEST": {"modelpreview_reads_test_env.h"},
}


def is_external(name: str) -> bool:
    return any(pattern.search(name) for pattern, _ in EXTERNAL)


def resolves(including: Path, name: str, active_macros: set) -> bool:
    candidates = [including.parent / name]
    candidates += [root / name for root in (SRC,) + SDK_ROOTS]
    candidates.append(ROOT / name)
    if any(name in HOSTED_TEST_BRANCHES[macro] for macro in active_macros):
        candidates.append(ROOT / "tests" / name)
    return any(candidate.is_file() for candidate in candidates)


def guarded_macros(text: str, name: str) -> set:
    """Macros on an enclosing #ifdef that name this include's hosted-test branch."""
    macros = set()
    for macro, names in HOSTED_TEST_BRANCHES.items():
        if name not in names:
            continue
        if re.search(rf"^\s*#\s*if(?:def)?\s+{macro}\b", text, re.M):
            macros.add(macro)
    return macros


def main() -> int:
    unresolved = []
    for path in sorted(SRC.rglob("*")):
        if path.suffix not in {".h", ".hpp", ".cpp", ".inl"} or not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for name in INCLUDE.findall(text):
            if is_external(name) or name in ALLOWED_UNRESOLVED:
                continue
            if not resolves(path, name, guarded_macros(text, name)):
                unresolved.append((path.relative_to(ROOT).as_posix(), name))

    if unresolved:
        for source, name in unresolved:
            print(f"FAIL: {source}: #include \"{name}\" does not resolve", file=sys.stderr)
        print(f"\n{len(unresolved)} unresolved quoted include(s) under src/", file=sys.stderr)
        return 1

    print("include resolution guard passed (every quoted src/ include resolves)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
